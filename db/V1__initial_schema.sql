CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    oidc_subject  TEXT        NOT NULL,
    display_name  TEXT        NOT NULL,
    source        TEXT        NOT NULL DEFAULT 'local',
    source_id     TEXT,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT app_user_oidc_subject_key UNIQUE (oidc_subject)
);


CREATE UNIQUE INDEX app_user_source_key
    ON app_user (source, source_id)
    WHERE source_id IS NOT NULL;


CREATE TABLE clan (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                TEXT        NOT NULL,
    tag                 TEXT        NOT NULL,
    description         TEXT,
    owner_id            BIGINT      NOT NULL REFERENCES app_user (id),
    visibility          TEXT        NOT NULL DEFAULT 'PUBLIC',
    requires_invitation BOOLEAN     NOT NULL DEFAULT FALSE,
    status              TEXT        NOT NULL DEFAULT 'ACTIVE',
    tag_color           TEXT,
    website_url         TEXT,
    source              TEXT        NOT NULL DEFAULT 'local',
    source_id           TEXT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at          TIMESTAMPTZ,
    CONSTRAINT clan_visibility_check CHECK (visibility IN ('PUBLIC', 'PRIVATE')),
    CONSTRAINT clan_status_check     CHECK (status IN ('ACTIVE', 'SUSPENDED')),
    CONSTRAINT clan_tag_length_check CHECK (char_length(tag) <= 3)
);


CREATE UNIQUE INDEX clan_tag_unique
    ON clan (lower(tag))
    WHERE deleted_at IS NULL;

CREATE UNIQUE INDEX clan_name_unique
    ON clan (lower(name))
    WHERE deleted_at IS NULL;

CREATE UNIQUE INDEX clan_source_key
    ON clan (source, source_id)
    WHERE source_id IS NOT NULL;

CREATE INDEX clan_owner_idx ON clan (owner_id);


CREATE TABLE clan_membership (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clan_id    BIGINT      NOT NULL REFERENCES clan (id) ON DELETE CASCADE,
    user_id    BIGINT      NOT NULL REFERENCES app_user (id),
    role       TEXT        NOT NULL DEFAULT 'MEMBER',
    joined_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    left_at    TIMESTAMPTZ,
    source     TEXT        NOT NULL DEFAULT 'local',
    source_id  TEXT,
    CONSTRAINT membership_role_check CHECK (role IN ('OWNER', 'MODERATOR', 'MEMBER'))
);


CREATE UNIQUE INDEX membership_one_active_per_user
    ON clan_membership (user_id)
    WHERE left_at IS NULL;

CREATE UNIQUE INDEX membership_source_key
    ON clan_membership (source, source_id)
    WHERE source_id IS NOT NULL;

CREATE INDEX membership_clan_idx ON clan_membership (clan_id) WHERE left_at IS NULL;


CREATE TABLE clan_invitation (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clan_id      BIGINT      NOT NULL REFERENCES clan (id) ON DELETE CASCADE,
    invitee_id   BIGINT      NOT NULL REFERENCES app_user (id),
    inviter_id   BIGINT      NOT NULL REFERENCES app_user (id),
    state        TEXT        NOT NULL DEFAULT 'PENDING',
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at   TIMESTAMPTZ NOT NULL,
    responded_at TIMESTAMPTZ,
    CONSTRAINT invitation_state_check
        CHECK (state IN ('PENDING', 'ACCEPTED', 'DECLINED', 'EXPIRED', 'REVOKED'))
);


CREATE UNIQUE INDEX invitation_one_pending
    ON clan_invitation (clan_id, invitee_id)
    WHERE state = 'PENDING';

CREATE INDEX invitation_invitee_idx ON clan_invitation (invitee_id);

CREATE VIEW clan_invitation_effective AS
SELECT i.*,
       CASE WHEN i.state = 'PENDING' AND i.expires_at <= now()
            THEN 'EXPIRED' ELSE i.state END AS effective_state
FROM clan_invitation i;


CREATE TABLE clan_event (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type       TEXT        NOT NULL,
    entity_id         BIGINT      NOT NULL,
    event_type        TEXT        NOT NULL,
    payload           JSONB       NOT NULL,
    actor_id          BIGINT      REFERENCES app_user (id),
    occurred_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    delivered_at      TIMESTAMPTZ,
    delivery_attempts INTEGER     NOT NULL DEFAULT 0,
    last_error        TEXT
);

CREATE INDEX clan_event_entity_idx   ON clan_event (entity_type, entity_id, occurred_at);
CREATE INDEX clan_event_undelivered  ON clan_event (occurred_at) WHERE delivered_at IS NULL;


CREATE RULE clan_event_no_update AS ON UPDATE TO clan_event DO INSTEAD NOTHING;
CREATE RULE clan_event_no_delete AS ON DELETE TO clan_event DO INSTEAD NOTHING;


CREATE TABLE clan_report (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clan_id      BIGINT      NOT NULL REFERENCES clan (id) ON DELETE CASCADE,
    reporter_id  BIGINT      NOT NULL REFERENCES app_user (id),
    category     TEXT        NOT NULL,
    reason       TEXT        NOT NULL,
    state        TEXT        NOT NULL DEFAULT 'OPEN',
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolved_at  TIMESTAMPTZ,
    resolved_by  BIGINT      REFERENCES app_user (id),
    CONSTRAINT report_category_check
        CHECK (category IN ('OFFENSIVE_NAME', 'OFFENSIVE_TAG', 'INAPPROPRIATE_CONTENT')),
    CONSTRAINT report_state_check CHECK (state IN ('OPEN', 'RESOLVED', 'DISMISSED'))
);

CREATE INDEX clan_report_open_idx ON clan_report (clan_id) WHERE state = 'OPEN';


CREATE TABLE moderation_action (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clan_id      BIGINT      NOT NULL REFERENCES clan (id) ON DELETE CASCADE,
    moderator_id BIGINT      NOT NULL REFERENCES app_user (id),
    action       TEXT        NOT NULL,
    reason       TEXT,
    report_id    BIGINT      REFERENCES clan_report (id),
    previous     JSONB,
    performed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT moderation_action_check
        CHECK (action IN ('SUSPEND', 'UNSUSPEND', 'RENAME', 'RETAG', 'DELETE', 'RESTORE'))
);

CREATE INDEX moderation_action_clan_idx ON moderation_action (clan_id, performed_at DESC);
CREATE INDEX moderation_action_by_idx   ON moderation_action (moderator_id, performed_at DESC);


CREATE VIEW clan_needing_attention AS
SELECT c.id,
       c.tag,
       c.name,
       c.status,
       (c.tag !~ '^[A-Za-z0-9]{1,3}$') AS tag_invalid,
       (btrim(c.name) = '')            AS name_empty,
       (btrim(c.tag)  = '')            AS tag_empty
FROM clan c
WHERE c.deleted_at IS NULL
  AND (c.tag !~ '^[A-Za-z0-9]{1,3}$' OR btrim(c.name) = '');
