ALTER TABLE clan ADD COLUMN motd_updated_at TIMESTAMPTZ;
ALTER TABLE clan ADD COLUMN logo_updated_at TIMESTAMPTZ;

-- the image bytes sit in their own table so a page of clan cards never drags them along
CREATE TABLE clan_logo (
    clan_id BIGINT PRIMARY KEY REFERENCES clan (id) ON DELETE CASCADE,
    content BYTEA NOT NULL,
    content_type TEXT NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT clan_logo_type_check CHECK (content_type IN ('image/png', 'image/jpeg', 'image/webp')),
    CONSTRAINT clan_logo_size_check CHECK (octet_length(content) <= 524288)
);

--dates a clan puts on its own calendar, nothing to do with the clan_event history table
CREATE TABLE clan_calendar_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clan_id BIGINT NOT NULL REFERENCES clan (id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    starts_at TIMESTAMPTZ NOT NULL,
    created_by BIGINT REFERENCES app_user (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT clan_calendar_title_check CHECK (btrim(title) <> '')
);

CREATE INDEX clan_calendar_event_clan_idx ON clan_calendar_event (clan_id, starts_at);

-- an invite carries the role it offers, and only the owner may offer moderator
ALTER TABLE clan_invitation ADD COLUMN role TEXT NOT NULL DEFAULT 'MEMBER';
ALTER TABLE clan_invitation ADD CONSTRAINT invitation_role_check CHECK (role IN ('MODERATOR', 'MEMBER'));
